// Writes the travel destinations from data/destinations.js into travel.html as plain HTML,
// so crawlers and link previews that don't run JavaScript still see every place.
// Visitors with JavaScript never see this block (CSS hides it under html.js); the
// interactive map/cards render as usual.
//
// Runs on every Cloudflare Pages deploy (build command: node scripts/prerender.mjs)
// and can be run locally. No dependencies. Also refreshes the travel <lastmod> in sitemap.xml.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, f), 'utf8');

const win = {};
new Function('window', read('data/destinations.js'))(win);
const { checked, sources, places } = win.BETSY_TRAVEL;

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const hrs = (h) => (h < 1 ? Math.round(h * 60) + ' min' : +h.toFixed(1) + (h === 1 ? ' hr' : ' hrs'));
const price = (o) => (o.mode === 'drive' && o.cost === 0 ? '$0 + human labour' : o.costText);
const date = (iso) => new Date(iso + 'T00:00:00Z').toLocaleDateString('en-AU', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });

const items = places.map((d) => {
  const opts = d.opts.map((o) => {
    const size = o.big === false ? ' Small dogs only.' : o.big === 'maybe' ? ' Check a big dog’s crate fits.' : '';
    return `<li>${esc(o.mode)}: ${esc(o.what)}, ${esc(price(o))} for the dog, about ${hrs(o.hrs)} one way.${o.note ? ' ' + esc(o.note) : ''}${size}</li>`;
  }).join('');
  const list = (arr) => arr.map((x) => `<li>${esc(x)}</li>`).join('');
  const src = d.src.filter((k) => sources[k]).map((k) => `<li><a href="${esc(sources[k].u)}">${esc(sources[k].t)}</a></li>`).join('');
  return `<article>
<h3>${esc(d.name)}</h3>
<p>${esc(d.where)}. ${esc(d.blurb)}</p>
<h4>How to get there with a dog</h4><ul>${opts}</ul>
<h4>She can</h4><ul>${list(d.yes)}</ul>
<h4>She can’t</h4><ul>${list(d.no)}</ul>
${d.tip ? `<p>Tip: ${esc(d.tip)}</p>\n` : ''}${src ? `<h4>Sources</h4><ul>${src}</ul>\n` : ''}</article>`;
}).join('\n');

const block = `<!-- prerender:start (generated by scripts/prerender.mjs from data/destinations.js; do not edit by hand) -->
<section class="prerender" aria-label="All destinations">
<h2>All ${places.length} places a dog can go from Melbourne</h2>
<p>Dog-side prices, one way, last checked ${date(checked)}.</p>
${items}
</section>
<!-- prerender:end -->`;

let html = read('travel.html');
const re = /<!-- prerender:start[\s\S]*?<!-- prerender:end -->/;
if (!re.test(html)) throw new Error('travel.html is missing the <!-- prerender:start --> / <!-- prerender:end --> markers');
html = html.replace(re, () => block);
writeFileSync(join(root, 'travel.html'), html);

let sm = read('sitemap.xml');
sm = sm.replace(/(<loc>https:\/\/betsy-site\.pages\.dev\/travel<\/loc><lastmod>)[^<]*/, `$1${checked}`);
writeFileSync(join(root, 'sitemap.xml'), sm);

console.log(`prerendered ${places.length} places into travel.html (checked ${checked})`);
